// Copies compiled ABIs + bytecode into the shared workspace as `as const` TypeScript so the
// indexer, web app and chaos runner get fully typed viem bindings without a codegen dependency.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifactsDir = resolve(here, "../artifacts/contracts");
const outDir = resolve(here, "../../shared/src/generated");

const targets = [
  { artifact: "Escrow.sol/Escrow.json", out: "escrow.ts", name: "escrow" },
  { artifact: "mocks/Mocks.sol/MockERC20.json", out: "mockErc20.ts", name: "mockErc20" },
];

await mkdir(outDir, { recursive: true });

for (const t of targets) {
  const json = JSON.parse(await readFile(resolve(artifactsDir, t.artifact), "utf8"));
  const body = [
    "// AUTO-GENERATED by packages/contracts/scripts/export-abi.mjs. Do not edit.",
    `export const ${t.name}Abi = ${JSON.stringify(json.abi, null, 2)} as const;`,
    "",
    `export const ${t.name}Bytecode = ${JSON.stringify(json.bytecode)} as const;`,
    "",
  ].join("\n");
  await writeFile(resolve(outDir, t.out), body);
  console.log(`wrote ${t.out} (${json.abi.length} ABI entries)`);
}
